"""Traces the approved logo (design/Minimalist Loop Infinity Wordmark.png) into smooth Bezier outlines.

Writes ios/Tools/loop-logo.json (used by make-app-icon.swift) and
ios/Loop/DesignSystem/Components/LoopLogoShape.swift (the in-app logo as a SwiftUI Shape).
Coordinates are in units of the artwork's width, y down, so the logo's height is `aspect`.
Needs numpy, pillow and potracer (`pip install potracer`); run from the repo root:
    python3 -I ios/Tools/trace-logo.py
"""
import json
import numpy as np
import potrace
from PIL import Image, ImageFilter

SRC = "design/Minimalist Loop Infinity Wordmark.png"
SCALE = 3   # upscale first so JPEG noise in the reference doesn't wobble the edges

img = Image.open(SRC).convert("L")
img = img.resize((img.width * SCALE, img.height * SCALE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(4))
ink = np.asarray(img) < 128
ys, xs = np.where(ink)
x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
ink = ink[y0:y1, x0:x1]
width, height = ink.shape[1], ink.shape[0]

paths = potrace.Bitmap(~ink).trace(turdsize=20, alphamax=1.0, opticurve=True, opttolerance=1.0)

def norm(p):
    return [round(p.x / width, 5), round(p.y / width, 5)]

contours = []
for curve in paths:
    segments = []
    for seg in curve.segments:
        if seg.is_corner:
            segments.append(["l"] + norm(seg.c))
            segments.append(["l"] + norm(seg.end_point))
        else:
            segments.append(["c"] + norm(seg.c1) + norm(seg.c2) + norm(seg.end_point))
    contours.append({"start": norm(curve.start_point), "segments": segments})

aspect = round(height / width, 5)
json.dump({"aspect": aspect, "contours": contours}, open("ios/Tools/loop-logo.json", "w"))

def fmt(v):
    return f"{v:.5f}"

lines = []
for contour in contours:
    sx, sy = contour["start"]
    lines.append(f"        path.move(to: p({fmt(sx)}, {fmt(sy)}))")
    for seg in contour["segments"]:
        if seg[0] == "l":
            lines.append(f"        path.addLine(to: p({fmt(seg[1])}, {fmt(seg[2])}))")
        else:
            lines.append(f"        path.addCurve(to: p({fmt(seg[5])}, {fmt(seg[6])}), control1: p({fmt(seg[1])}, {fmt(seg[2])}), control2: p({fmt(seg[3])}, {fmt(seg[4])}))")
    lines.append("        path.closeSubpath()")

swift = f'''import SwiftUI

// GENERATED by ios/Tools/trace-logo.py from the approved logo artwork. Do not edit by hand.

/// The Loop logo outline: "Loop" with the two o's drawn as one continuous infinity shape.
/// Fill it with the even-odd rule (`LoopLogo` does), because the counters are holes.
struct LoopLogoShape: Shape {{
    /// Height divided by width of the artwork.
    static let aspect: CGFloat = {fmt(aspect)}

    func path(in rect: CGRect) -> Path {{
        let scale = min(rect.width, rect.height / Self.aspect)
        let originX = rect.midX - scale / 2
        let originY = rect.midY - scale * Self.aspect / 2
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: originX + x * scale, y: originY + y * scale) }}
        var path = Path()
{chr(10).join(lines)}
        return path
    }}
}}
'''
open("ios/Loop/DesignSystem/Components/LoopLogoShape.swift", "w").write(swift)
print("aspect", aspect, "contours", len(contours), "segments", sum(len(c["segments"]) for c in contours))
